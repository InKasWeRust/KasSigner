use firmware_tools::{sign_bip340_hash, sign_firmware_hash, sign_test_firmware_hash};

#[test]
fn generator_matches_bip340_vector_zero_and_production_verifier() {
    let private_key = [
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03,
    ];
    let message = [0u8; 32];
    let public_key = [
        0xF9, 0x30, 0x8A, 0x01, 0x92, 0x58, 0xC3, 0x10,
        0x49, 0x34, 0x4F, 0x85, 0xF8, 0x9D, 0x52, 0x29,
        0xB5, 0x31, 0xC8, 0x45, 0x83, 0x6F, 0x99, 0xB0,
        0x86, 0x01, 0xF1, 0x13, 0xBC, 0xE0, 0x36, 0xF9,
    ];
    let expected = [
        0xE9, 0x07, 0x83, 0x1F, 0x80, 0x84, 0x8D, 0x10,
        0x69, 0xA5, 0x37, 0x1B, 0x40, 0x24, 0x10, 0x36,
        0x4B, 0xDF, 0x1C, 0x5F, 0x83, 0x07, 0xB0, 0x08,
        0x4C, 0x55, 0xF1, 0xCE, 0x2D, 0xCA, 0x82, 0x15,
        0x25, 0xF6, 0x6A, 0x4A, 0x85, 0xEA, 0x8B, 0x71,
        0xE4, 0x82, 0xA7, 0x4F, 0x38, 0x2D, 0x2C, 0xE5,
        0xEB, 0xEE, 0xE8, 0xFD, 0xB2, 0x17, 0x2F, 0x47,
        0x7D, 0xF4, 0x90, 0x0D, 0x31, 0x05, 0x36, 0xC0,
    ];

    let generated = sign_bip340_hash(&private_key, &message).unwrap();
    assert_eq!(generated, expected);
    let signature = offline_signer::crypto::schnorr::SchnorrSignature { bytes: generated };
    offline_signer::crypto::schnorr::schnorr_verify(&public_key, &message, &signature).unwrap();

    // The generic standards path verifies through the production verifier,
    // while the release path additionally rejects keys that do not match the
    // public release identity compiled into firmware.
    assert!(sign_firmware_hash(&private_key, &message).is_err());
}


#[test]
fn development_generator_matches_embedded_test_identity() {
    let private_key = *include_bytes!("../../../tools/build/firmware/dev_test_signing_key.bin");
    let message = [0x47u8; 32];
    let generated = sign_test_firmware_hash(&private_key, &message).unwrap();
    let signature = offline_signer::crypto::schnorr::SchnorrSignature { bytes: generated };

    offline_signer::crypto::schnorr::schnorr_verify(
        &signer_firmware_core::update::release::DEV_TEST_PUBKEY,
        &message,
        &signature,
    )
    .unwrap();

    // A repository-public development key must never satisfy the production
    // release identity check.
    assert!(sign_firmware_hash(&private_key, &message).is_err());
}
