#!/bin/sh
# KasSigner — Air-gapped offline signing device for Kaspa
# Copyright (C) 2025-2026 KasSigner Project (kassigner@proton.me)
# License: GPL-3.0-or-later
#
# The third-party notices of what is released: the SDK packages', shipped by
# an app beside the browser package or the native library and their own
# `LICENSE` (MPL-2.0), and the firmware's, beside the units' images.
#
#   sh release/notices.sh           write them
#   sh release/notices.sh --check   compare with what is committed; CI runs it
#
# Runs from any folder, once `fork.sh` has put the P4's esp-hal fork in
# place, without which cargo cannot read the workspace. Needs cargo-about at
# the version below (`cargo install cargo-about --version 0.8.2 --locked`),
# which collects the license files of every crate compiled in, under
# `about.toml` (the SDK packages) or `about-firmware.toml` (the firmware)
# beside this script.
#
# Writes `THIRD_PARTY_NOTICES` in each one's crate folder, from where it is
# copied beside what is built:
#
#   crates/kassigner-sdk-wasm   the browser package, by its `build.sh`
#   crates/kassigner-sdk-ffi    the native library, by its `build.sh`
#   firmware/kassigner-signer   the firmware, one file for every board, by
#                               `release/build.sh`
#
# Added by hand, not being crates cargo-about sees: the Rust standard
# library, compiled into all three; rusty-kaspa at the commit
# `kassigner-kaspa` pins, whose rules and test vectors the Kaspa crates
# follow and are checked against (`kassigner-kaspa/tests/upstream.rs`); and
# for the firmware, the fonts and icons drawn on the screen, Bosch's BMI270
# microcode (M5Stack) and ESP-IDF, of which the bootloaders are built. Each
# license file is read where the tree keeps it.
#
# A new dependency or version changes the notices, and `--check` fails until
# they are written again, so they never fall behind the lock.

set -eu

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
ABOUT_VERSION="0.8.2"
MODE="${1:-write}"

have="$(cargo about --version 2>/dev/null | awk '{ print $2 }' || true)"
if [ "$have" != "$ABOUT_VERSION" ]; then
    echo "cargo-about $ABOUT_VERSION is needed; found '${have:-none}':" >&2
    echo "    cargo install cargo-about --version $ABOUT_VERSION --locked" >&2
    exit 1
fi

SDK_OWN="is KasSigner's own code, under the Mozilla Public License 2.0 (LICENSE,
beside this file). It is built from, and ships with, the third-party
software below, each under its own license, reproduced here as each one
requires."

FIRMWARE="The KasSigner firmware for every board (kassigner-<version>-<board>.bin
and kassigner-<version>-<board>-full.bin) and the Secure Boot bootloaders
released with it (kassigner-<version>-<chip>-secure-bootloader.bin)"

FIRMWARE_OWN="is KasSigner's own code, under the GNU General Public License, version 3
or later (COPYING, beside this file in a release and at the repository's
root), with the crates it shares with the SDK under the Mozilla Public
License 2.0, whose text and this release's source are in the repository at
the release's tag, <https://github.com/InKasWeRust/KasSigner>. It is built
from, and ships with, the third-party software below, each under its own
license, reproduced here as each one requires."

FONTS="firmware/kassigner-fw/assets/fonts"

section() {
    printf '%s\n' "================================================================================"
    printf '%s\n\n' "$1"
}

# The text before the sections: $1 what the notices are for, $2 how its own
# code is licensed.
opening() {
    printf 'THIRD-PARTY NOTICES\n\n%s\n\n%s\n\n' "$1" "$2"
    printf '%s\n%s\n\n' \
        "Generated by release/notices.sh from the repository's Cargo.lock with" \
        "cargo-about $ABOUT_VERSION; not to be edited by hand."
}

# A license file the tree keeps, under its heading: $1 the heading, $2 where
# it comes from, $3 the file. `awk 1` ends a last line left open, as Bosch's
# file leaves it.
kept() {
    section "$1"
    printf '%s\n\n' "$2"
    awk 1 "$3"
    printf '\n'
}

# rusty-kaspa, which every file carries.
kaspa() {
    kept "rusty-kaspa 2.1.0 (ISC), whose rules and test vectors the Kaspa code follows" \
        "<https://github.com/kaspanet/rusty-kaspa>, commit 01b532e8b553523216471682649693af92f0fd16" \
        "$HERE/notices/rusty-kaspa-LICENSE"
}

# The crates compiled in: $1 the crate's folder, $2 the configuration beside
# this script, then any of cargo's options.
crates() {
    dir="$1"
    config="$2"
    shift 2
    section "The crates compiled in"
    cargo about generate --locked -c "$HERE/$config" "$@" \
        -m "$ROOT/$dir/Cargo.toml" "$HERE/about.hbs"
}

# An SDK package's notices on stdout: $1 its crate's folder, $2 what it is.
sdk() {
    opening "$2" "$SDK_OWN"
    kept "The Rust standard library (MIT OR Apache-2.0), compiled in" \
        "Used under MIT. <https://github.com/rust-lang/rust>" \
        "$HERE/notices/rust-LICENSE-MIT"
    kaspa
    crates "$1" about.toml
}

# The firmware's notices on stdout, every board's crates at once: $1 its
# crate's folder.
firmware() {
    opening "$FIRMWARE" "$FIRMWARE_OWN"
    kept "The Rust standard library's core and alloc (MIT OR Apache-2.0), compiled in" \
        "Used under MIT. <https://github.com/rust-lang/rust>" \
        "$HERE/notices/rust-LICENSE-MIT"
    kaspa
    kept "Lato (SIL Open Font License 1.1), drawn as the screen's text" \
        "$FONTS: Lato-Regular.ttf, Lato-Bold.ttf" \
        "$ROOT/$FONTS/OFL-Lato.txt"
    kept "Oswald (SIL Open Font License 1.1), drawn as the screen's text" \
        "$FONTS: Oswald-Bold.ttf" \
        "$ROOT/$FONTS/OFL-Oswald.txt"
    kept "Rubik (SIL Open Font License 1.1), drawn as the screen's text" \
        "$FONTS: Rubik-Bold.ttf, Google Fonts' variable Rubik at weight 700" \
        "$ROOT/$FONTS/OFL-Rubik.txt"
    kept "Iconoir (MIT), drawn as the screen's icons" \
        "<https://github.com/iconoir-icons/iconoir>" \
        "$ROOT/firmware/kassigner-fw/assets/icons/LICENSE-iconoir.txt"
    kept "BMI270 Sensor API v2.86.1 (BSD-3-Clause), its microcode, in the M5Stack firmware" \
        "<https://github.com/boschsensortec/BMI270_SensorAPI>, commit d270cdee303b2ed9ea4c43fb7064da8ded8a48b4" \
        "$ROOT/vendor/bmi270/LICENSE"
    kept "ESP-IDF (Apache-2.0), of which the bootloaders are built" \
        "The Secure Boot bootloaders: ESP-IDF v6.1, <https://github.com/espressif/esp-idf>,
commit fff9895c82d744c7237be8847347bdd1b07c6643. The plain bootloader in
each kassigner-<version>-<board>-full.bin is ESP-IDF's as espflash ships it." \
        "$HERE/notices/esp-idf-LICENSE"
    crates "$1" about-firmware.toml --no-default-features --features "m5stack waveshare p4"
}

# One file's notices on stdout, from the arguments `notices` takes.
made() {
    case "$1" in
        sdk) sdk "$2" "$3" ;;
        firmware) firmware "$2" ;;
    esac
}

# One file, written or checked: $1 sdk or firmware, $2 its crate's folder,
# $3 for an SDK package, what it is.
notices() {
    file="$ROOT/$2/THIRD_PARTY_NOTICES"
    if [ "$MODE" = "--check" ]; then
        if ! made "$@" | cmp -s - "$file"; then
            echo "$file is not current: sh release/notices.sh" >&2
            status=1
        fi
    else
        made "$@" > "$file"
        echo "wrote $file ($(wc -l < "$file") lines)"
    fi
}

status=0
notices sdk crates/kassigner-sdk-wasm "The KasSigner SDK's browser package (kassigner_sdk)"
notices sdk crates/kassigner-sdk-ffi "The KasSigner SDK's native library (kassigner_sdk_ffi)"
notices firmware firmware/kassigner-signer
exit "$status"
